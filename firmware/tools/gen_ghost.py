#!/usr/bin/env python3
"""Generate the semi-transparent jelly-ghost silhouette used by the pet UI.

Run with: PYTHONPATH=../../.tools/pyfont python3 tools/gen_ghost.py
Outputs components/pet_ui/src/ghost_art.c and /tmp/ghost_preview.png.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "components/pet_ui/src/ghost_art.c"
PREVIEW = Path("/tmp/ghost_preview.png")
W = H = 220

def build() -> Image.Image:
    mask = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(mask)
    # rounded top + straight sides
    d.ellipse((10, 0, 210, 200), fill=235)
    d.rectangle((10, 100, 210, 170), fill=235)
    # three soft bottom lobes (classic ghost skirt)
    for cx in (52, 110, 168):
        d.ellipse((cx - 38, 132, cx + 38, 208), fill=235)
    mask = mask.filter(ImageFilter.GaussianBlur(1.2))

    img = Image.new("RGBA", (W, H), (255, 255, 255, 0))
    src = img.load()
    m = mask.load()
    for y in range(H):
        for x in range(W):
            a = m[x, y]
            if a:
                src[x, y] = (255, 255, 255, a)

    bbox = img.getbbox()
    crop = img.crop(bbox)
    canvas = Image.new("RGBA", (W, H), (255, 255, 255, 0))
    canvas.paste(crop, ((W - crop.width) // 2, (H - crop.height) // 2))
    return canvas

def main() -> None:
    img = build()
    img.save(PREVIEW)
    rgba = img.tobytes()
    out = bytearray(len(rgba))
    # LVGL ARGB8888 memory order is B, G, R, A.
    for i in range(0, len(rgba), 4):
        r, g, b, a = rgba[i:i + 4]
        out[i:i + 4] = bytes((b, g, r, a))

    lines = []
    for i in range(0, len(out), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in out[i:i + 16])
        lines.append("    " + chunk + ",")
    body = "\n".join(lines)
    c = f'''/* Auto-generated by tools/gen_ghost.py. Do not edit by hand. */
#include "lvgl.h"

#define GHOST_W {W}
#define GHOST_H {H}

LV_ATTRIBUTE_MEM_ALIGN
static const uint8_t ghost_map[] = {{
{body}
}};

const lv_image_dsc_t ghost_art = {{
    .header.magic = LV_IMAGE_HEADER_MAGIC,
    .header.cf = LV_COLOR_FORMAT_ARGB8888,
    .header.w = GHOST_W,
    .header.h = GHOST_H,
    .header.stride = GHOST_W * 4,
    .data_size = GHOST_W * GHOST_H * 4,
    .data = ghost_map,
}};
'''
    OUT.write_text(c)
    print(f"generated {OUT} ({OUT.stat().st_size} bytes), preview {PREVIEW}")

if __name__ == "__main__":
    main()
